const emptyCard = (name: string): Battlecard => ({
  why_we_win: [
    "Integrated operating partner: EOR, dedicated capability and advisory under one accountable team",
    "Regional delivery ownership with senior oversight rather than staffing-only placement",
  ],
  why_we_lose: [`${name} may hold incumbent relationships or brand recognition in the buyer's market`],
  objections: [
    {
      objection: `"${name} is already on our shortlist."`,
      response:
        "Compare equivalent scope: supervision, compliance ownership, reporting and exit terms — not the headline rate.",
    },
  ],
  landmines: ["Who owns quality and reporting when a resource underperforms?", "What is included in the quoted fee, and what is extra?"],
  proof_points: ["ISO 27001 and ISO 9001 (verify claim dates)", "ACCA Approved Employer status (verify)"],
});

function mk(
  c: Partial<Competitor> & {
    id: string;
    name: string;
    website: string;
    tier: CompetitorTier;
    kind: CompetitorKind;
    arenas: Arena[];
    countries: CountryCode[];
    positioning: string;
    implication: string;
    threat_inputs: Competitor["threat_inputs"];
  },
): Competitor {
  return {
    hq: "To verify",
    size_band: "To verify",
    segments: ["SME", "Mid-market"] as Segment[],
    certifications: [],
    strengths: [],
    weaknesses: [],
    evidence_coverage: 0.25,
    battlecard: emptyCard(c.name),
    provenance: {
      source_url: c.website,
      source_type: "company_website",
      observed_at: SEED_DATE,
      confidence: "low",
      verification_status: "unverified",
      analyst: ANALYST,
    },
    ...c,
  };
}

